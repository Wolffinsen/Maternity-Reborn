function normalizarPrecio(valor) {
  if (typeof valor === "number") return valor;

  const texto = String(valor ?? "0").trim();
  if (!texto) return 0;

  const valores = texto.match(/\d[\d,\.\s]*/g) || [];
  if (!valores.length) return 0;

  const primerValor = valores[0].replace(/[^\d]/g, "");
  const numero = Number(primerValor || 0);

  return Number.isFinite(numero) ? numero : 0;
}

function normalizarIncluye(valor) {
  if (Array.isArray(valor)) return valor;
  if (typeof valor === "string" && valor.trim()) return [valor.trim()];
  return ["Bebé Reborn con ropita, chupón y cobija."];
}

function normalizarCertificacion(valor) {
  if (valor && typeof valor === "object") {
    return {
      texto: valor.texto || "Certificado de autenticidad y calidad del material.",
      archivoUrl: valor.archivoUrl || "#"
    };
  }

  return {
    texto: "Certificado de autenticidad y calidad del material.",
    archivoUrl: "#"
  };
}

function normalizarCuidados(valor) {
  if (Array.isArray(valor) && valor.length) return valor;
  return [
    "Limpia la piel con un paño ligeramente humedecido y sin productos químicos.",
    "Evita la luz solar directa y el calor excesivo para proteger la pintura.",
    "Mantén el pelo peinado con peine suave y agua únicamente.",
    "No uses gorros ni colas para evitar que dañe el pelo injertado."
  ];
}

function normalizarDiseno(item, index) {
  const nombre = item?.nombre || `Diseño ${index + 1}`;
  const categoria = Array.isArray(item?.categorias) && item.categorias.length ? item.categorias[0] : "recien_nacido";

  return {
    id: Number(item?.id ?? index + 1),
    nombre,
    slug: item?.slug || `${nombre.toLowerCase().replace(/\s+/g, "-")}-${index + 1}`,
    descripcion: item?.descripcion || `Bebé Reborn ${nombre}.`,
    precio: normalizarPrecio(item?.precio ?? 0),
    imagen: item?.imagen || "assets/img/diseno-1.jpg",
    disponible: item?.disponible !== false,
    subtitulo: item?.subtitulo || `${categoria.replace(/_/g, " ")} · ${item?.diseno || "Diseño"}`,
    talla: item?.talla || "Talla estándar",
    material: item?.material || "Vinilo reborn",
    cabello: item?.cabello || "Detalle pintado / mohair según diseño.",
    incluye: normalizarIncluye(item?.incluye),
    fotos: Array.isArray(item?.fotos) && item.fotos.length ? item.fotos : [item?.imagen || "assets/img/diseno-1.jpg"],
    categorias: Array.isArray(item?.categorias) && item.categorias.length ? item.categorias : [categoria],
    certificacion: normalizarCertificacion(item?.certificacion),
    cuidados: normalizarCuidados(item?.cuidados)
  };
}

